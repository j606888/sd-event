/**
 * 把 Markdown 壓成單純文字，供列表卡片等只需要摘要的地方使用
 * （卡片上的 `# 標題`、`**粗體**` 符號本身沒有意義，只會佔掉行數）。
 */
export function stripMarkdown(input: string): string {
  return input
    .replace(/```[\s\S]*?```/g, " ")          // 程式碼區塊
    .replace(/`([^`]*)`/g, "$1")              // 行內程式碼
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1") // 圖片 → alt
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")  // 連結 → 文字
    .replace(/^\s{0,3}>+\s?/gm, "")           // 引言
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")       // 標題
    .replace(/^\s{0,3}(?:\*\s*){3,}$|^\s{0,3}(?:-\s*){3,}$|^\s{0,3}(?:_\s*){3,}$/gm, "") // 分隔線
    .replace(/^\s{0,3}([-*+]|\d+[.)])\s+/gm, "")        // 清單項目符號
    .replace(/(\*\*|__)(.*?)\1/g, "$2")       // 粗體
    .replace(/(\*|_)(?!\s)(.*?)(?<!\s)\1/g, "$2") // 斜體
    .replace(/~~(.*?)~~/g, "$1")              // 刪除線
    .replace(/\s+/g, " ")
    .trim();
}
